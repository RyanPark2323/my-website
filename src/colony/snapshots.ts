/**
 * Warm start.
 *
 * The field is never shown cold. On load we pick one of a small pool of baked
 * steady states, apply one of the eight square symmetries, jitter the sources,
 * start the tick counter at a random offset, and let the colony settle onto the
 * seeded trails before the first frame is drawn.
 *
 * A pool of five, times eight symmetries, times continuous jitter, is
 * effectively unrepeatable — which is the point. Nothing here is a scripted
 * path: the seed is a pheromone field, and every trail you see after the
 * settle was walked by an agent.
 *
 * The pool itself is generated by scripts/gen-snapshots.mjs, which runs the
 * engine in this same file's dependency — not a lookalike.
 */

import {
  createColony,
  rasterizeBars,
  scatterAnts,
  stepColony,
  type Bar,
  type Colony,
  type ColonyOpts,
} from './engine';
import { SNAPSHOTS } from './snapshots.data';

export interface Snapshot {
  /** Side of the stored (downsampled) field. */
  g: number;
  /** Value that quantized byte 255 represents. */
  scale: number;
  /** g*g bytes, base64. */
  field: string;
  /** [x, y, supply] per source. */
  sources: [number, number, number][];
  /** [x, y, len, thick, angle] per obstacle. */
  bars: [number, number, number, number, number][];
  nest: [number, number];
  deliveries: number;
}

/** Ticks of real simulation run before the first frame, so nothing pops. */
const SETTLE_TICKS = 300;
const SETTLE_DT = 1000 / 30;

function decodeBytes(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/** One of the eight symmetries of the square: k quarter-turns, then an optional mirror. */
function symmetryGrid(src: Float32Array, g: number, k: number, mirror: boolean): Float32Array {
  const dst = new Float32Array(g * g);
  for (let y = 0; y < g; y++) {
    for (let x = 0; x < g; x++) {
      let tx = x;
      let ty = y;
      for (let r = 0; r < k; r++) {
        const nx = g - 1 - ty;
        ty = tx;
        tx = nx;
      }
      if (mirror) tx = g - 1 - tx;
      dst[ty * g + tx] = src[y * g + x];
    }
  }
  return dst;
}

/** The same transform applied to an oriented bar. */
function symmetryBar(b: Bar, k: number, mirror: boolean): Bar {
  let { x, y, angle } = b;
  for (let r = 0; r < k; r++) {
    const nx = 1 - y;
    y = x;
    x = nx;
    angle += Math.PI / 2;
  }
  if (mirror) {
    x = 1 - x;
    angle = Math.PI - angle;
  }
  return { x, y, angle, len: b.len, thick: b.thick };
}

function symmetryPoint(x: number, y: number, k: number, mirror: boolean): [number, number] {
  let tx = x;
  let ty = y;
  for (let r = 0; r < k; r++) {
    const nx = 1 - ty;
    ty = tx;
    tx = nx;
  }
  if (mirror) tx = 1 - tx;
  return [tx, ty];
}

function upsample(src: Float32Array, g: number, G: number): Float32Array {
  const dst = new Float32Array(G * G);
  for (let y = 0; y < G; y++) {
    const sy = ((y * g) / G) | 0;
    for (let x = 0; x < G; x++) {
      const sx = ((x * g) / G) | 0;
      dst[y * G + x] = src[sy * g + sx];
    }
  }
  return dst;
}

/**
 * Build a colony already in motion. Returns it after the settle, so the
 * caller's first draw is of a living field.
 */
export function warmColony(opts: ColonyOpts = {}): Colony {
  const c = createColony(opts);
  const rng = c.rng;

  const snap = SNAPSHOTS[(rng() * SNAPSHOTS.length) | 0] as Snapshot;
  const k = (rng() * 4) | 0;
  const mirror = rng() < 0.5;

  // Field: decode, orient, scale up to this session's grid.
  const bytes = decodeBytes(snap.field);
  const seed = new Float32Array(snap.g * snap.g);
  const q = snap.scale / 255;
  for (let i = 0; i < seed.length; i++) seed[i] = bytes[i] * q;
  const oriented = symmetryGrid(seed, snap.g, k, mirror);
  c.field = upsample(oriented, snap.g, c.G);
  c.tmp = new Float32Array(c.G * c.G);

  // Nest and sources travel with the field.
  const [nx, ny] = symmetryPoint(snap.nest[0], snap.nest[1], k, mirror);
  c.nest = { x: nx, y: ny };

  // Walls travel with the field, so the seeded trails still route around them.
  c.bars = (snap.bars ?? []).map(([bx, by, len, thick, angle]) =>
    symmetryBar({ x: bx, y: by, len, thick, angle }, k, mirror)
  );
  rasterizeBars(c);

  c.sources = [];
  c.nextId = 1;
  for (const [sxRaw, syRaw, supply] of snap.sources) {
    const [sx, sy] = symmetryPoint(sxRaw, syRaw, k, mirror);
    const jx = Math.min(0.94, Math.max(0.06, sx + (rng() - 0.5) * 0.024));
    const jy = Math.min(0.94, Math.max(0.06, sy + (rng() - 0.5) * 0.024));
    c.sources.push({
      id: c.nextId++,
      x: jx,
      y: jy,
      supply,
      visitor: false,
      bornMs: 0,
      // Sources in a warm field have already been found. This is the copy
      // correction §3 asks for: nothing reads UNFOUND on load.
      found: true,
      relocatedMs: -1,
      rho: 0,
      wasQuiet: false,
    });
  }

  // A warm colony has history. Start the counters where they would be.
  c.tick = 40_000 + ((rng() * 860_000) | 0);
  c.deliveries = snap.deliveries + ((rng() * 400) | 0);

  scatterAnts(c);
  for (let i = 0; i < SETTLE_TICKS; i++) stepColony(c, SETTLE_DT);

  // The settle is prologue, not content: no annotation may fire from it, and
  // the disturbance clock starts from the settled state, not from zero.
  c.events.length = 0;
  c.lastEventKind = null;
  c.lastEventMs = -1e9;
  c.nextEventMs = c.simMs + 60_000 + rng() * 60_000;

  return c;
}
